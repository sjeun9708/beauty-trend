def ranks(d: str, age: str) -> list[dict]:
    """연령별 기본 순서에 날마다 작은 흔들림을 더해, 실제처럼 서서히 움직이는 순위를 만듭니다."""
    base = random.Random(f"base-{age}")
    # 기본 키워드는 상위권, '선크림 추천' 같은 파생 검색어는 그 아래에 분포
    scores = {k: base.random() * 60 + (0 if k in KEYWORDS else 10 + base.random() * 60 if k in BRAND_KWS
                                          else 40 + base.random() * 500) for k in POOL}
    day = date.fromisoformat(d).toordinal()
    for k in POOL:
        wave = random.Random(f"{age}-{k}")
        phase, amp = wave.random() * 6.28, wave.choice([3, 5, 8, 18])
        scores[k] += amp * math.sin(day / 3 + phase) + random.Random(f"{d}-{age}-{k}").random() * 4
    kws = sorted(POOL, key=lambda k: scores[k])
    return [{"rank": i + 1, "keyword": k} for i, k in enumerate(kws[:config.COLLECT_N])]


def analysis(keyword: str) -> dict:
    rng = random.Random(keyword)
    cat = rng.choice(list(REASONS))
    sources = [] if cat == "스테디셀러" else [
        {"title": f"(데모) {keyword} 관련 기사 제목 예시", "link": "https://example.com"},
        {"title": f"(데모) {keyword} 후기 블로그", "link": "https://example.com"},
    ][: rng.choice([1, 2])]
    conf = "low" if cat == "스테디셀러" else rng.choice(["high", "medium"])
    return {"category": cat, "reason": REASONS[cat], "confidence": conf, "sources": sources}


